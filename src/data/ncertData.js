export const CLASS_STREAMS = {
  "Class 11": SENIOR_STREAMS,
  "Class 12": SENIOR_STREAMS,
};

export function streamsFor(className) {
  const streams = CLASS_STREAMS[className];
  return streams ? Object.keys(streams) : [];
}

export function subjectsFor(className, stream) {
  const available = [...new Set([
    ...librarySubjects(className),
    ...Object.keys(ncertSyllabus[className] || {}),
  ])];
  const streams = CLASS_STREAMS[className];
  if (!streams) return available;
  const names = streams[stream] || streams.Science;
  return names.filter((name) => available.includes(name));
}

export function hasTextbook(className, subject) {
  return libraryChapters(className, subject).length > 0;
}

export function chaptersFor(className, subject) {
  const fromBooks = libraryChapters(className, subject);
  if (fromBooks.length) return fromBooks.map((chapter) => chapter.label);
  return ncertSyllabus[className]?.[subject] || [];
}

export function chapterScopeLabel(picked, bookChapters) {
  const list = (picked || []).filter(Boolean);
  if (!list.length) return '';
  const book = bookChapters || [];
  const whole = book.length > 0 && list.length === book.length && book.every((name) => list.includes(name));
  if (whole) return 'Whole book';
  if (list.length === 1) return list[0];
  return `${list.length} chapters`;
}
